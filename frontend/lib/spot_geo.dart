/// 球面距离（公里），haversine
double distKm(double lat1, double lng1, double lat2, double lng2) {
  const r = 6371.0;
  final dLat = (lat2 - lat1) * math.pi / 180;
  final dLng = (lng2 - lng1) * math.pi / 180;
  final a = math.sin(dLat / 2) * math.sin(dLat / 2) +
      math.cos(lat1 * math.pi / 180) *
          math.cos(lat2 * math.pi / 180) *
          math.sin(dLng / 2) *
          math.sin(dLng / 2);
  return 2 * r * math.asin(math.sqrt(a));
}

/// 当前位置附近的景区：(名字, 距离km)，按距离升序，最多 [limit] 个。
/// 跨省重名的景区只保留最近的那处。
List<(String, double)> nearbySpots(
  double lat,
  double lng, {
  double maxKm = 50,
  int limit = 8,
}) {
  final all = <(String, double)>[
    for (final (name, la, lo) in spotGeo)
      if (distKm(lat, lng, la, lo) <= maxKm) (name, distKm(lat, lng, la, lo)),
  ]..sort((a, b) => a.$2.compareTo(b.$2));
  final seen = <String>{};
  return [
    for (final e in all)
      if (seen.add(e.$1)) e,
  ].take(limit).toList();
}
